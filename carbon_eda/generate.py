"""Stage 1a: flow CSV + config/materials.yaml spx_colors + tech.yaml -> spx batch files.

outputs/<tech>/spx/
  materials.py   set_materials(): every spx material in config/materials.yaml (spx_colors)
  clip.py        set_clip(): route, clip window and layout (also for each carrier route
                 and each other route of the flow CSV)
  route.py       create_route(): flow, modules and steps, with a meas_save_3D
                 after every step (tdr/<stem>.tdr) and a TBSON checkpoint at the
                 end of every module (tbson/<route>.tbson, overwritten); before them,
                 the carrier routes listed ahead of it in tech.yaml routes:. Carbon-only
                 steps run as no-op custom steps, steps with no spx parameters with
                 0 values (spxsteps, config/spx_steps.yaml)
  run.py         runner for `spx -nodisplay -runpy`
outputs/<tech>/manifest.json
                 one entry per step: index, CSV seq/module/step, tdr and image stem
"""

import datetime
import json
import re

from . import csvio, spxsteps
from .carbon import Config
from .carbon.mpw import step_materials
from .paths import rel, tool

CHECKPOINT_STEP = 'save_tbson'
SAVE_STEP = 'save_tdr_{:04d}'
# Custom metrology step body. Runs inside spx.procedural.run once the module's
# steps are computed; saves to a temp file first so a failed save never
# clobbers the previous checkpoint.
CHECKPOINT_SCRIPT = '''
def save_tbson_checkpoint(**kwargs):
    import os
    import spx
    path = {paths!r}[kwargs['Route']]
    tmp = path + '.tmp'
    with spx.util.file(tmp, Overwrite=True) as f:
        spx.procedural.save(File=f, Location={{'Route': kwargs['Route']}})
    os.replace(tmp, path)
    print(f"TBSON checkpoint after module {{kwargs['Module']}}: {{path}}")
    return {{}}
'''
# Body of the custom step a carbon-only step type (clean, marking, ...) runs as in spx.
NOOP_SCRIPT = 'def {name}(**kwargs):\n    return kwargs["ClipState"]\n'

RUNNER = '''\
# Generated by carbon_eda. Run with:
#   {command}
import os

import spx

SPX_DIR = {spx_dir!r}
ROUTES = {routes!r}
TBSON = {tbson!r}


def _load(name):
    path = os.path.join(SPX_DIR, name)
    ns = {{}}
    exec(compile(open(path).read(), path, 'exec'), ns)
    return ns


def main():
    _load('materials.py')['set_materials']()
    _load('clip.py')['set_clip']()
    _load('route.py')['create_route']()
    # In order: tech.yaml carrier wafers, then the flow CSV's routes. A wafer that a
    # bond_structure step bonds on top runs before the route that bonds it.
    for route in ROUTES:
        if not spx.procedural.run(Route=route):
            raise RuntimeError(f'SPX run of route {{route}} failed')
    # The checkpoint at the end of the last module already holds the finished route.
    print(f'Done. TBSON: {{TBSON}}')


if __name__ == '__main__':
    main()
'''


def _kwargs(kw):
    return ''.join(f'{k}={csvio.pyrepr(v)},' for k, v in kw.items())


def materials_py(colors):
    out = ['# Generated by carbon_eda from config/materials.yaml spx_colors.\n\n',
           'def set_materials():\n', '    import spx\n\n']
    for name, color in colors.items():
        out.append(f"    spx.procedural.material(Location={{'Material': {name!r}}}, "
                   f"{_kwargs({'Color': color} if color else {})})\n")
    return ''.join(out)


def clip_py(route, clip, layout, others=()):
    """set_clip(): the route and its clip, then each other route (carriers, the flow CSV's other
    routes) with the same clip."""
    coords = [float(c) for c in clip['coords']]
    clip_id = f"{str(layout).replace('/', '|')}||{{{' '.join(f'{c:g}' for c in coords)}}}"
    out = [f'# Generated by carbon_eda from tech.yaml.\n\n'
           f'def set_clip():\n'
           f'    import spx\n\n']
    for r in [route, *others]:
        out.append(f'    route_loc = {{"Route": {r!r}}}\n'
                   f'    spx.procedural.route(Location=route_loc, )\n'
                   f'    spx.procedural.clip(Location={{"Route": {r!r}, "Clip": {clip_id!r}}}, '
                   f'Coords={coords!r},LayoutFile={str(layout)!r},Name={clip.get("name", "clip")!r},)\n')
        if r == route:
            out.append(f"    spx.procedural.layout(Layout='layout', Path={str(layout)!r})\n")
        out.append("    spx.util.update_clip_layout(route_loc, 'layout')\n")
    out.append(f'    return {{"Route": {route!r}}}\n')
    return ''.join(out)


def bond_routes(flow):
    """Routes the flow's bond_structure steps bond onto (their BondTopStep: an spx location, or
    just the name of a route: a route of the flow CSV or a carrier in tech.yaml routes:)."""
    out = set()
    for s in flow.steps:
        if s.step_type == 'bond_structure':
            text = s.cells.get('BondTopStep', '')
            out |= set(re.findall(r"'Route':\s*'([^']+)'", text)) or {text}
    return out - {''}


def bond_target(flow, csv_route, name):
    """BondTopStep for bonding a route of the flow CSV on top: its last step that is not a meas_save_3D."""
    s = [s for s in flow.steps if s.route == csv_route and s.step_type != 'meas_save_3D'][-1]
    return step_location({'Flow': s.flow, 'Module': s.module, 'Route': name, 'Step': s.name})


def carrier_target(c):
    """BondTopStep for bonding a carrier wafer (a tech.yaml routes: entry) on top: its substrate step."""
    return step_location({'Flow': c['flow'], 'Module': c['module'], 'Route': c['route'], 'Step': c['step']})


def step_location(loc):
    return csvio.Raw(f'(parameter_reflection.description.Map_like_string_string({loc!r}),)')


def carrier_calls(carriers):
    """spx calls creating each carrier route's flow, module and substrate step (tech.yaml routes)."""
    out = []
    for c in carriers:
        loc = {'Route': c['route'], 'Flow': c['flow']}
        params = {k: csvio.decode(k, str(v)) for k, v in (c.get('substrate') or {}).items()}
        out += [csvio.emit_call('flow', loc, {}), csvio.emit_call('module', dict(loc, Module=c['module']), {}),
                csvio.emit_call('substrate', dict(loc, Module=c['module'], Step=c['step']), params)]
    return out


def noop_calls(s, loc):
    """A step type spx doesn't have, as a custom step that returns the structure unchanged; customstep
    takes no Comment, so a modify call sets it."""
    out = [csvio.emit_call('customstep', loc, {
        'Description': f'Carbon-accounting {s.step_type} step: no geometry change', 'Name': s.step_type, 'Parameters': [],
        'Script': csvio.Raw(f'noop_step_scripts[{s.step_type!r}]'), 'StepType': 'process_step'})]
    if s.comment:
        out.append(f"    spx.procedural.modify(Target={{'ProcessStep': {loc!r}}}, Comment={s.comment!r},)\n")
    return out


def route_py(route, flow, tdr_dir, tbson, carriers=None):
    """route: the tech.yaml route, for rows with no route of their own; tbson: its checkpoint
    (each other route of the flow CSV gets <route>.tbson next to it); tdr_dir None: no 3D saves."""
    out = ['# Generated by carbon_eda from the flow CSV.\n\n',
           'def create_route():\n', '    import spx\n', '    import qupy\n',
           '    import parameter_reflection  # noqa: F401  (BondTopStep cells)\n\n']
    if carriers:
        out.append('    # carrier routes (tech.yaml routes): one substrate step each\n')
        out += carrier_calls(carriers)
        out.append('\n')
    out.append('    # flow, modules\n')
    out += [csvio.emit_call('flow', {'Route': r or route, 'Flow': f}, {}) for r, f in flow.flows]
    out += [csvio.emit_call('module', {'Route': m.route or route, 'Flow': m.flow, 'Module': m.name}, m.params)
            for m in flow.modules]
    names = {r or route: r for r in flow.routes}
    carrier_routes = {c['route']: c for c in carriers or ()}
    paths = {name: str(tbson.with_name(f'{name}.tbson')) for name in names}
    noop = sorted({s.step_type for s in flow.steps if s.spx_kind == 'custom_noop'})
    if noop:
        out.append(f'\n    noop_step_scripts = {({t: NOOP_SCRIPT.format(name=t) for t in noop})!r}\n')
    out.append("\n    tbson_checkpoint_script = r'''" + CHECKPOINT_SCRIPT.format(paths=paths) + "'''\n")
    out.append(f'\n    # steps{", each followed by a 3D save" if tdr_dir else ""}; a TBSON checkpoint ends each module\n')
    for i, s in enumerate(flow.steps):
        loc = {'Route': s.route or route, 'Flow': s.flow, 'Module': s.module}
        params, signature = s.spx_params
        top = s.cells.get('BondTopStep') if s.step_type == 'bond_structure' else None
        if top in names:
            params = dict(params, BondTopStep=bond_target(flow, names[top], top))
        elif top in carrier_routes:
            params = dict(params, BondTopStep=carrier_target(carrier_routes[top]))
        if s.zero_filled:
            params = {**params, **s.zero_filled, 'Comment': ' | '.join(filter(None, [s.comment, spxsteps.ZERO_NOTE]))}
        if s.spx_kind == 'custom_noop':
            out += noop_calls(s, dict(loc, Step=s.name))
        elif s.step_type == 'customstep' and 'Comment' in params:   # customstep takes no Comment
            comment = params.pop('Comment')
            out.append(csvio.emit_call(s.step_type, dict(loc, Step=s.name), params))
            out.append(f"    spx.procedural.modify(Target={{'ProcessStep': {dict(loc, Step=s.name)!r}}}, "
                       f"Comment={comment!r},)\n")
        else:
            out.append(csvio.emit_call(s.step_type, dict(loc, Step=s.name), params))
        if signature:
            out.append(csvio.emit_call('signature', dict(loc, Step=s.name), signature))
        if tdr_dir:
            out.append(csvio.emit_call('meas_save_3D', dict(loc, Step=SAVE_STEP.format(s.index)), {
                'Path': str(tdr_dir / f'{s.stem}.tdr'), 'Transformation': 'rename_tcad_compatible'}))
        nxt = flow.steps[i + 1] if i + 1 < len(flow.steps) else None
        last = not nxt or (nxt.route, nxt.flow, nxt.module) != (s.route, s.flow, s.module)
        if last:
            out.append(f'    spx.procedural.customstep(Location={dict(loc, Step=CHECKPOINT_STEP)!r}, '
                       "Description='Save route TBSON checkpoint',Name='save_tbson_checkpoint',"
                       "Parameters=[],Script=tbson_checkpoint_script,StepType='metrology',)\n")
    out.append('\n    return {"Route": %r}\n' % route)
    return ''.join(out)


def manifest(tech, flow, layout):
    return {
        'tech': tech.name,
        'route': tech.route,
        'routes': [r or tech.route for r in flow.routes],
        'csv': rel(tech.csv),
        'layout': rel(layout),
        'generated': datetime.datetime.now().isoformat(timespec='seconds'),
        'steps': [{'index': s.index, 'seq': s.seq, 'route': s.route or tech.route, 'flow': s.flow, 'module': s.module, 'step': s.name,
                   'step_type': s.step_type, 'comment': s.comment, 'stem': s.stem,
                   'tdr': f'tdr/{s.stem}.tdr', 'spx': s.spx_kind, 'zero_filled': sorted(s.zero_filled)}
                  for s in flow.steps],
    }


def run(tech, limit=None, zero_fill=False):
    """zero_fill: agree in advance to steps with no spx parameters running with 0 values (else asked)."""
    flow = csvio.load_flow(tech.csv)
    if limit:
        flow.truncate(limit)
    try:
        spxsteps.classify(flow)
    except ValueError as e:
        raise SystemExit(f'spx cannot run these rows:\n{e}')
    mismatch = spxsteps.version_mismatch()
    if mismatch:
        print(f'WARNING: {mismatch}')
    spxsteps.confirm(tech.name, flow, zero_fill)
    cfg = tech.cfg
    if 'clip' not in cfg:
        raise SystemExit(f'{tech.tech_yaml}: no clip section')
    layout = tech.layout.resolve()
    materials = Config().spx_colors
    missing = sorted({m for s in flow.steps for col in s.params for m in step_materials(s.value(col))} - set(materials))
    if missing:
        print(f'WARNING: the flow uses materials with no spx_colors entry in config/materials.yaml: {", ".join(missing)}')

    carriers = tech.routes[:-1]
    routes = [r or tech.route for r in flow.routes]
    if tech.route not in routes:
        raise SystemExit(f'{tech.tech_yaml}: route {tech.route!r} is not a route of {tech.csv.name} '
                         f'({", ".join(routes)}); set route: to the one that ends the flow')
    clash = sorted({c['route'] for c in carriers} & set(routes))
    if clash:
        raise SystemExit(f'{tech.tech_yaml}: {", ".join(clash)} is both a carrier in routes: and a route of {tech.csv.name}')
    missing = sorted(bond_routes(flow) - {c['route'] for c in carriers} - set(routes))
    if missing:
        raise SystemExit(f'{tech.tech_yaml}: bond_structure steps bond onto {", ".join(missing)}; '
                         f'list them in routes: before {tech.route!r}')
    for s in flow.steps:
        top = s.cells.get('BondTopStep') if s.step_type == 'bond_structure' else None
        if top in routes and routes.index(top) >= routes.index(s.route or tech.route):
            raise SystemExit(f'{tech.csv}:{s.line}: {s.name!r} bonds route {top!r} on top, so the rows of '
                             f'{top!r} must come before those of {s.route or tech.route!r}')

    for d in (tech.spx_dir, tech.tdr_dir, tech.tbson_dir):
        d.mkdir(parents=True, exist_ok=True)
    tbson = tech.tbson_dir / f'{tech.route}.tbson'
    runner = tech.spx_dir / 'run.py'
    (tech.spx_dir / 'materials.py').write_text(materials_py(materials))
    others = [c['route'] for c in carriers] + [r for r in routes if r != tech.route]
    (tech.spx_dir / 'clip.py').write_text(clip_py(tech.route, cfg['clip'], layout, others))
    (tech.spx_dir / 'route.py').write_text(route_py(tech.route, flow, tech.tdr_dir, tbson, carriers))
    command = tool('spx', f'-nodisplay -exitOnError -log {tech.spx_dir / "run.log"} -runpy {runner}')
    runner.write_text(RUNNER.format(command=command, spx_dir=str(tech.spx_dir),
                                    routes=[c['route'] for c in carriers] + routes, tbson=str(tbson)))
    tech.manifest.write_text(json.dumps(manifest(tech, flow, layout), indent=1))
    print(f'{tech.spx_dir}: route{"s" if len(routes) > 1 else ""} {", ".join(map(repr, routes))}, {len(flow.modules)} modules, {len(flow.steps)} steps'
          f'{f" (first {limit})" if limit else ""}, {len(materials)} materials')
    print(f'{tech.manifest}: {len(flow.steps)} steps')
    return flow
