"""Flow CSV rows spx can't run as written: carbon-only steps (clean, marking, ...) and built-in
steps with no spx parameters (anneal, dopant implant_ellipsoid). See config/spx_steps.yaml.

Each step gets an spx_kind:
  as_csv       sent to spx as the CSV has it
  custom_noop  no spx.procedural function and no spx parameters: a no-op custom step
  zero_filled  no spx parameters: its type's zero_fill cells (Step.zero_filled), once agreed to
               unless the type has ask: false

    python -m carbon_eda spx-functions    list the installed spx's functions in config/spx_steps.yaml
"""

import re
import subprocess
import sys
import tempfile
from collections import Counter
from pathlib import Path

from . import csvio
from .paths import CONFIG_DIR, load_yaml, tool, tools_config

SPX_STEPS_YAML = CONFIG_DIR / 'spx_steps.yaml'
GENERATED = '# ---- generated by `python -m carbon_eda spx-functions`'
ZERO_NOTE = 'CarbonEDA: missing spx parameters set to 0'
VERSION_RE = re.compile(r'[A-Z]-\d{4}\.\d{2}(?:-SP\d+)?')
DUMP = '''\
import spx
names = sorted(n for n in dir(spx.procedural) if not n.startswith('_') and callable(getattr(spx.procedural, n)))
open({out!r}, 'w').write('\\n'.join(names) + '\\n')
'''


def config(path=SPX_STEPS_YAML):
    cfg = load_yaml(path)
    cfg['functions'] = set(cfg.get('functions') or ())
    cfg['zero_fill'] = {t: _zero_fill(path, t, entry) for t, entry in (cfg.get('zero_fill') or {}).items()}
    cfg['parameterless'] = set(cfg.get('parameterless') or ())
    return cfg


def _zero_fill(path, step_type, entry):
    """One zero_fill entry as {'ask': bool, 'cells': {column: decoded cell}}."""
    entry = entry if isinstance(entry, dict) else {}
    extra = sorted(set(entry) - {'ask', 'cells'})
    ask = entry.get('ask', True)
    if extra or not isinstance(ask, bool) or not isinstance(entry.get('cells'), dict):
        raise SystemExit(f'{path}: zero_fill: {step_type}: needs cells: (its spx parameters) and optionally '
                         'ask: false' + (f'; {", ".join(extra)} should be under cells:' if extra else ''))
    return {'ask': ask, 'cells': {col: csvio.decode(col, str(v)) for col, v in entry['cells'].items()}}


def asks(cfg, step_type):
    """Whether a zero-filled step of this type is a geometry gap: make spx asks before running it and
    the report lists it (zero_fill ask:, default true)."""
    return (cfg['zero_fill'].get(step_type) or {}).get('ask', True)


def classify(flow, cfg=None):
    """Set spx_kind and zero_filled on every step; a ValueError (file:line) names the rows spx can't run."""
    cfg = cfg or config()
    errors = []
    for s in flow.steps:
        given = sorted(set(s.params) - {'Comment'})
        where = f'{flow.csv_path}:{s.line} {s.name!r} ({s.step_type})'
        if s.step_type not in cfg['functions']:
            if given:
                errors.append(f'{where}: spx has no step type {s.step_type!r} (config/spx_steps.yaml functions), '
                              f'but the row sets spx parameters {", ".join(given)}')
            s.spx_kind = 'custom_noop'
        elif given or s.step_type in cfg['parameterless']:
            s.spx_kind = 'as_csv'
        elif s.step_type in cfg['zero_fill']:
            s.spx_kind, s.zero_filled = 'zero_filled', cfg['zero_fill'][s.step_type]['cells']
        else:
            errors.append(f'{where}: no spx parameters; set them in the CSV, or add {s.step_type} to zero_fill or '
                          'parameterless in config/spx_steps.yaml')
    if errors:
        raise ValueError('\n'.join(errors))
    return flow


def counts(steps, kind):
    """'9 anneal, 29 implant_ellipsoid' for the steps of one spx_kind."""
    return ', '.join(f'{n} {t}' for t, n in sorted(Counter(s.step_type for s in steps if s.spx_kind == kind).items()))


def summary(name, flow):
    """One line on the no-op and zero-filled steps of a classified flow ('' if none)."""
    noop = sum(s.spx_kind == 'custom_noop' for s in flow.steps)
    zero = sum(s.spx_kind == 'zero_filled' for s in flow.steps)
    parts = ([f'{zero} steps have no spx parameters ({counts(flow.steps, "zero_filled")}) and will run with 0 values '
              '(no change to the structure)'] if zero else []) + \
            ([f'{noop} carbon-only steps ({counts(flow.steps, "custom_noop")}) run as no-op custom steps'] if noop else [])
    return f'{name}: {"; ".join(parts)}' if parts else ''


def confirm(name, flow, agreed, stdin=None, cfg=None):
    """Lists the zero-filled steps of the types that ask (zero_fill ask:) and asks before spx runs them
    with 0 values (agreed: --zero-fill)."""
    stdin = stdin or sys.stdin
    cfg = cfg or config()
    zero = [s for s in flow.steps if s.spx_kind == 'zero_filled' and asks(cfg, s.step_type)]
    line = summary(name, flow)
    if line:
        print(line)
    if not zero or agreed:
        return
    for s in zero:
        print(f'  {flow.csv_path}:{s.line} {s.name} ({s.step_type})')
    model = f'Add their parameters to {Path(flow.csv_path).name} to model them.'
    if not stdin.isatty():
        raise SystemExit(f'{model} No terminal to ask at, so stopped: rerun with --zero-fill (make ZERO_FILL=1) '
                         'to run them with 0 values.')
    print(f'{model} Continue with 0 values? [y/N] ', end='', flush=True)
    if stdin.readline().strip().lower() not in ('y', 'yes'):
        raise SystemExit('stopped: no 0 values agreed to')


def version_mismatch():
    """Why config/spx_steps.yaml may not list the spx that tools.yaml runs ('' if it does)."""
    listed = str(load_yaml(SPX_STEPS_YAML).get('spx_version', ''))
    setup = (tools_config().get('tools', {}).get('spx') or {}).get('setup') or ''
    used = VERSION_RE.findall(setup)
    if used and listed not in used:
        return (f'config/spx_steps.yaml lists the functions of spx {listed}, but config/tools.yaml loads {used[0]}: '
                'rerun python -m carbon_eda spx-functions')
    return ''


def write_functions(names, version, path=SPX_STEPS_YAML):
    """Rewrite the generated part of config/spx_steps.yaml."""
    head = path.read_text().split(GENERATED)[0]
    rows, row = [], []
    for n in names:
        if row and len(', '.join(row + [n])) > 100:
            rows.append(row)
            row = []
        row.append(n)
    rows.append(row)
    body = ''.join(f'  {", ".join(r)},\n' for r in rows)
    path.write_text(f'{head}{GENERATED}, which rewrites everything below this line\n'
                    f'spx_version: {version}\nfunctions: [\n{body}]\n')


def dump_functions():
    """Run spx once and list its spx.procedural functions in config/spx_steps.yaml."""
    setup = (tools_config().get('tools', {}).get('spx') or {}).get('setup') or ''
    version = (VERSION_RE.findall(setup) or ['unknown'])[0]
    with tempfile.TemporaryDirectory() as tmp:
        out, script = Path(tmp) / 'functions.txt', Path(tmp) / 'dump.py'
        script.write_text(DUMP.format(out=str(out)))
        cmd = f'cd {tmp} && ' + tool('spx', f'-nodisplay -exitOnError -log {tmp}/dump.log -runpy {script}')
        rc = subprocess.run(['bash', '-lc', cmd], stdout=subprocess.DEVNULL, stderr=subprocess.STDOUT).returncode
        if rc or not out.exists():
            raise SystemExit(f'spx exited with {rc} and listed no functions ({cmd})')
        names = out.read_text().split()
    write_functions(names, version)
    print(f'{SPX_STEPS_YAML}: {len(names)} spx.procedural functions of spx {version}')
